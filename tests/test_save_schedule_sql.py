"""Tests for db/save_schedule.sql against a real Postgres.

Skipped unless TEST_DATABASE_URL points at a throwaway database, e.g.
    TEST_DATABASE_URL=postgresql://postgres@127.0.0.1:55432/postgres pytest tests/test_save_schedule_sql.py
Each test rebuilds the tables, so never point this at a database you care about.
"""

from __future__ import annotations

import json
import os
import threading
from pathlib import Path

import pytest

psycopg = pytest.importorskip("psycopg")
URL = os.environ.get("TEST_DATABASE_URL")
pytestmark = pytest.mark.skipif(not URL, reason="TEST_DATABASE_URL not set")

SQL = (Path(__file__).resolve().parents[1] / "db" / "save_schedule.sql").read_text()

COLUMNS = """
  wo text, quote text, po_number text, status text, customer_name text,
  model_description text, scheduled_date date, completion_date date,
  price numeric, uploaded_name text, created_at timestamptz default now()
"""


def setup_schema(conn, id_type="bigint generated by default as identity", meta_key="key text primary key"):
    conn.execute(
        """
        do $$ begin
          if not exists (select 1 from pg_roles where rolname = 'anon') then create role anon; end if;
          if not exists (select 1 from pg_roles where rolname = 'authenticated') then create role authenticated; end if;
        end $$;
        """
    )
    conn.execute("drop table if exists public.order_book, public.app_meta cascade")
    conn.execute("drop function if exists public.save_schedule(text, jsonb, jsonb)")
    conn.execute(f"create table public.order_book (id {id_type} primary key, {COLUMNS})")
    conn.execute(f"create table public.app_meta ({meta_key}, value text)")


@pytest.fixture
def conn():
    with psycopg.connect(URL, autocommit=True) as c:
        setup_schema(c)
        yield c


def migrate(conn):
    conn.execute(SQL)


def save(conn, expected, upserts=(), deletes=()):
    return conn.execute(
        "select public.save_schedule(%s, %s::jsonb, %s::jsonb)",
        (expected, json.dumps(list(upserts)), json.dumps(list(deletes))),
    ).fetchone()[0]


def row(wo, day="2026-10-10", **extra):
    data = {
        "wo": wo, "quote": f"Q-{wo}", "po_number": "", "status": "Open", "customer_name": "Acme Corp",
        "model_description": "Van", "scheduled_date": day, "completion_date": None, "price": 100.5,
        "uploaded_name": "test.xlsx",
    }
    data.update(extra)
    return data


def orders(conn):
    return conn.execute("select id::text, wo, scheduled_date::text from public.order_book order by id").fetchall()


def version(conn):
    return conn.execute("select value from public.app_meta where key = 'data_version'").fetchone()[0]


def test_inserts_updates_deletes_and_bumps_version(conn):
    migrate(conn)
    assert version(conn) == "0"
    assert save(conn, "0", [row("100"), row("101"), row("102")]) == "1"
    (id100, _, _), (id101, _, _), (id102, _, _) = orders(conn)

    assert save(conn, "1", [dict(row("100", "2026-10-12"), id=id100)], deletes=[id102]) == "2"
    assert orders(conn) == [(id100, "100", "2026-10-12"), (id101, "101", "2026-10-10")]
    saved_at = conn.execute("select value::timestamptz from public.app_meta where key = 'data_saved_at'").fetchone()[0]
    assert saved_at is not None


def test_existing_timestamp_version_keeps_counting(conn):
    conn.execute("insert into public.app_meta values ('data_version', '1770769807')")
    migrate(conn)
    assert save(conn, "1770769807", [row("100")]) == "1770769808"


def test_stale_version_is_refused_and_nothing_changes(conn):
    migrate(conn)
    save(conn, "0", [row("100")])
    with pytest.raises(psycopg.Error) as err:
        save(conn, "0", [row("999")], deletes=[orders(conn)[0][0]])
    assert err.value.sqlstate == "PT409"
    assert [r[1] for r in orders(conn)] == ["100"]
    assert version(conn) == "1"


def test_failure_part_way_rolls_everything_back(conn):
    migrate(conn)
    save(conn, "0", [row("100"), row("101")])
    keep_id = orders(conn)[0][0]
    with pytest.raises(psycopg.Error):
        # The delete and the first insert would succeed; the bad date fails the whole save.
        save(conn, "1", [row("200"), row("201", "not-a-date")], deletes=[keep_id])
    assert [r[1] for r in orders(conn)] == ["100", "101"]
    assert version(conn) == "1"


def test_two_saves_at_once_cannot_both_win(conn):
    migrate(conn)
    save(conn, "0", [row("100")])
    first = psycopg.connect(URL)  # holds its transaction open
    save(first, "1", [row("from-first")])

    outcome = {}

    def second_save():
        with psycopg.connect(URL, autocommit=True) as c:
            try:
                outcome["version"] = save(c, "1", [row("from-second")])
            except psycopg.Error as e:
                outcome["error"] = e.sqlstate

    t = threading.Thread(target=second_save)
    t.start()
    t.join(timeout=1)
    assert t.is_alive(), "second save should wait for the first"
    first.commit()
    first.close()
    t.join(timeout=10)

    assert outcome == {"error": "PT409"}
    assert [r[1] for r in orders(conn)] == ["100", "from-first"]


def test_uuid_ids(conn):
    setup_schema(conn, id_type="uuid default gen_random_uuid()")
    migrate(conn)
    save(conn, "0", [row("100"), row("101")])
    (a, _, _), (b, _, _) = sorted(orders(conn), key=lambda r: r[1])
    save(conn, "1", [dict(row("100", "2026-10-20"), id=a)], deletes=[b])
    assert [(r[1], r[2]) for r in orders(conn)] == [("100", "2026-10-20")]


def test_app_meta_without_unique_key(conn):
    setup_schema(conn, meta_key="id bigint generated by default as identity primary key, key text")
    migrate(conn)
    migrate(conn)  # running the script twice must not add a second version row
    assert conn.execute("select count(*) from public.app_meta").fetchone()[0] == 1
    assert save(conn, "0", [row("100")]) == "1"
    assert save(conn, "1", [row("101")]) == "2"
    assert conn.execute("select count(*) from public.app_meta").fetchone()[0] == 2  # version + saved_at
